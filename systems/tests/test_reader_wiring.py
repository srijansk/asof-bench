def test_no_module_outside_the_tests_is_one_that_pytest_collects():
    # pytest imports any file named test_*.py or *_test.py that it finds under the directory it is
    # given, so a module of the systems' own must not be named so.
    collected = ("test_*.py", "*_test.py")
    found = [path.relative_to(SYSTEMS) for path in SYSTEMS.rglob("*.py")
             if "tests" not in path.relative_to(SYSTEMS).parts[:1]
             and "__pycache__" not in path.parts
             and any(fnmatch.fnmatch(path.name, pattern) for pattern in collected)]
    assert found == []


def test_ci_runs_the_answering_tests_with_the_sdk_and_httpx_that_the_lock_pins():
    workflow = SYSTEMS.parent / ".github" / "workflows" / "tests.yml"
    if not workflow.is_file():
        pytest.skip("the repository's workflows are not beside systems/ here")
    pins = lock_pins()
    step = (f"--extra dev --with anthropic=={pins['anthropic']} --with httpx=={pins['httpx']} "
            "python -m pytest systems/tests/test_answer.py systems/tests/test_llm_client.py "
            "systems/tests/test_grep_agent.py")
    assert step in workflow.read_text(encoding="utf-8")
